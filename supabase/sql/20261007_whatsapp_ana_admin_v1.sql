CREATE OR REPLACE FUNCTION public.ops2_ana_admin_load_v1()
RETURNS jsonb LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, private AS $$
  SELECT jsonb_build_object(
    'ok', true,
    'draft', (SELECT jsonb_build_object('configuration', d.configuration, 'revision', d.revision, 'updated_at', d.updated_at)
              FROM private.whatsapp_ana_admin_draft_v1 d WHERE d.singleton),
    'active', (SELECT jsonb_build_object('id', v.id, 'version', v.version, 'configuration', v.configuration, 'created_at', v.created_at)
               FROM private.whatsapp_ana_admin_runtime_v1 r JOIN private.whatsapp_ana_admin_versions_v1 v ON v.id = r.active_version_id WHERE r.singleton),
    'versions', (SELECT coalesce(jsonb_agg(jsonb_build_object('id', v.id, 'version', v.version, 'actor_id', v.actor_id, 'change_note', v.change_note, 'created_at', v.created_at) ORDER BY v.version DESC), '[]'::jsonb)
                 FROM (SELECT * FROM private.whatsapp_ana_admin_versions_v1 ORDER BY version DESC LIMIT 20) v),
    'test_runs', (SELECT coalesce(jsonb_agg(jsonb_build_object('id', t.id, 'draft_revision', t.draft_revision, 'scenario_keys', t.scenario_keys, 'passed_count', t.passed_count, 'failed_count', t.failed_count, 'safe_reasons', t.safe_reasons, 'latency_ms', t.latency_ms, 'created_at', t.created_at) ORDER BY t.created_at DESC), '[]'::jsonb)
                  FROM (SELECT * FROM private.whatsapp_ana_admin_test_runs_v1 ORDER BY created_at DESC LIMIT 20) t),
    'events', (SELECT coalesce(jsonb_agg(jsonb_build_object('action', e.action, 'actor_id', e.actor_id, 'version_id', e.version_id, 'draft_revision', e.draft_revision, 'channel_key', e.channel_key, 'detail', e.detail, 'created_at', e.created_at) ORDER BY e.created_at DESC), '[]'::jsonb)
               FROM (SELECT * FROM private.whatsapp_ana_admin_events_v1 ORDER BY created_at DESC LIMIT 30) e)
  );
$$;

CREATE OR REPLACE FUNCTION public.ops2_ana_admin_save_draft_v1(p_configuration jsonb, p_expected_revision bigint, p_note text DEFAULT '', p_actor_id uuid DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, private AS $$
DECLARE current_row private.whatsapp_ana_admin_draft_v1%ROWTYPE;
BEGIN
  IF jsonb_typeof(p_configuration) <> 'object' OR jsonb_typeof(p_configuration->'behavior') <> 'object'
     OR jsonb_typeof(p_configuration->'knowledge') <> 'array' OR jsonb_typeof(p_configuration->'triggers') <> 'array'
     OR jsonb_typeof(p_configuration->'test_cases') <> 'array' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'configuration_shape_invalid');
  END IF;
  SELECT * INTO current_row FROM private.whatsapp_ana_admin_draft_v1 WHERE singleton FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok', false, 'error', 'draft_missing'); END IF;
  IF current_row.revision <> p_expected_revision THEN
    RETURN jsonb_build_object('ok', false, 'error', 'revision_conflict', 'revision', current_row.revision);
  END IF;
  UPDATE private.whatsapp_ana_admin_draft_v1 SET configuration = p_configuration, revision = revision + 1,
    updated_at = now(), updated_by = p_actor_id WHERE singleton RETURNING * INTO current_row;
  INSERT INTO private.whatsapp_ana_admin_events_v1(action, actor_id, draft_revision, detail)
    VALUES ('draft_saved', p_actor_id, current_row.revision, jsonb_build_object('note', left(coalesce(p_note,''),240)));
  RETURN jsonb_build_object('ok', true, 'revision', current_row.revision, 'updated_at', current_row.updated_at);
END;
$$;

CREATE OR REPLACE FUNCTION public.ops2_ana_admin_publish_v1(p_test_run_id uuid, p_note text DEFAULT '', p_actor_id uuid DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, private AS $$
DECLARE d private.whatsapp_ana_admin_draft_v1%ROWTYPE; t private.whatsapp_ana_admin_test_runs_v1%ROWTYPE;
  next_version integer; new_id bigint;
BEGIN
  SELECT * INTO d FROM private.whatsapp_ana_admin_draft_v1 WHERE singleton FOR UPDATE;
  SELECT * INTO t FROM private.whatsapp_ana_admin_test_runs_v1 WHERE id = p_test_run_id;
  IF NOT FOUND OR t.draft_revision <> d.revision OR t.failed_count <> 0 OR t.passed_count = 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'test_run_missing_stale_or_failed');
  END IF;
  SELECT coalesce(max(version),0)+1 INTO next_version FROM private.whatsapp_ana_admin_versions_v1;
  INSERT INTO private.whatsapp_ana_admin_versions_v1(version, configuration, actor_id, change_note)
    VALUES(next_version, d.configuration, p_actor_id, left(coalesce(p_note,''),240)) RETURNING id INTO new_id;
  INSERT INTO private.whatsapp_ana_admin_runtime_v1(singleton, active_version_id, updated_at, updated_by)
    VALUES(true,new_id,now(),p_actor_id)
    ON CONFLICT(singleton) DO UPDATE SET active_version_id=excluded.active_version_id,updated_at=excluded.updated_at,updated_by=excluded.updated_by;
  INSERT INTO private.whatsapp_ana_admin_events_v1(action,actor_id,version_id,draft_revision,detail)
    VALUES('published',p_actor_id,new_id,d.revision,jsonb_build_object('version',next_version,'test_run_id',p_test_run_id,'note',left(coalesce(p_note,''),240)));
  RETURN jsonb_build_object('ok',true,'version',next_version,'version_id',new_id,'draft_revision',d.revision);
END;
$$;

CREATE OR REPLACE FUNCTION public.ops2_ana_admin_rollback_v1(p_version_id bigint, p_note text DEFAULT '', p_actor_id uuid DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, private AS $$
DECLARE target private.whatsapp_ana_admin_versions_v1%ROWTYPE;
BEGIN
  SELECT * INTO target FROM private.whatsapp_ana_admin_versions_v1 WHERE id=p_version_id;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'error','version_not_found'); END IF;
  INSERT INTO private.whatsapp_ana_admin_runtime_v1(singleton,active_version_id,updated_at,updated_by)
    VALUES(true,target.id,now(),p_actor_id)
    ON CONFLICT(singleton) DO UPDATE SET active_version_id=excluded.active_version_id,updated_at=excluded.updated_at,updated_by=excluded.updated_by;
  INSERT INTO private.whatsapp_ana_admin_events_v1(action,actor_id,version_id,detail)
    VALUES('rolled_back',p_actor_id,target.id,jsonb_build_object('version',target.version,'note',left(coalesce(p_note,''),240)));
  RETURN jsonb_build_object('ok',true,'version',target.version,'version_id',target.id);
END;
$$;

