  failed_count integer NOT NULL CHECK (failed_count >= 0),
  safe_reasons jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(safe_reasons) = 'array'),
  latency_ms integer NOT NULL DEFAULT 0 CHECK (latency_ms >= 0),
