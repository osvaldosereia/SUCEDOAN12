create table if not exists public.agent_core_legacy_router_observations (
  id bigint generated by default as identity primary key,
  ai_job_id uuid not null unique references public.ai_jobs(id) on delete cascade,
  conversation_id uuid not null,
  message_id uuid,
  action text not null,
  router_family text not null,
  match_source text not null check (match_source in ('interactive','text','unknown')),
  interactive_id text,
  observed_at timestamptz not null default now()
);

alter table public.agent_core_legacy_router_observations enable row level security;
revoke all on table public.agent_core_legacy_router_observations from public, anon, authenticated;
grant select, insert, update, delete on table public.agent_core_legacy_router_observations to service_role;

