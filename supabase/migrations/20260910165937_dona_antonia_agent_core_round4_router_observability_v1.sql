    when 'basket_payment_selection' then 'basket_payment_checkout'
    when 'address_flow_reopened' then 'basket_payment_checkout'
    when 'address_flow_cancelled' then 'basket_payment_checkout'
    when 'legacy_address_escape_to_payment' then 'basket_payment_checkout'
    when 'legacy_address_escape_to_extras' then 'basket_payment_checkout'
    when 'basket_customer_data_processed' then 'basket_payment_checkout'
    when 'change_basket_delivery_address_flow' then 'basket_payment_checkout'
    when 'basket_payment_clarification' then 'basket_payment_checkout'
    when 'basket_final_confirmation' then 'basket_payment_checkout'
    when 'basket_payment_missing' then 'basket_payment_checkout'
    when 'basket_order_confirmed' then 'basket_payment_checkout'
    when 'basket_final_confirmation_repeat' then 'basket_payment_checkout'
    when 'basket_ready_for_human' then 'checkout_flow'
