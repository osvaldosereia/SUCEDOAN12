import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const source=fs.readFileSync('vitrine/admin/components/printing.js','utf8');
const runtime=fs.readFileSync('vitrine/admin/admin-runtime.js','utf8');
const tag='<script src="/vitrine/admin/components/printing.js?v=refactor-20261018"></script>';
assert.ok(html.includes(tag));
assert.ok(html.indexOf(tag)<html.indexOf('<script src="/vitrine/admin/admin-runtime.js?'));
assert.ok(runtime.includes('const openPrint=window.DonaAntoniaAdminPrinting.createOpenPrint(toast,esc);'));
assert.equal(runtime.includes('  function openPrint(title,body,mode,existingWindow=null){'),false);
assert.match(runtime,/ops_print_presented_failed/,'non-blocking print acknowledgement errors should remain visible');
let written='',closed=false,opened=false,toastText='';
const popup={document:{open(){opened=true},write(v){written+=v},close(){closed=true}}};
const context={window:{open:()=>popup},Object};
vm.runInNewContext(source,context);
const openPrint=context.window.DonaAntoniaAdminPrinting.createOpenPrint(v=>toastText=v,v=>String(v).replaceAll('<','&lt;').replaceAll('>','&gt;'));
openPrint('Pedido <123>','<b>OK</b>','delivery');
assert.ok(opened&&closed);
assert.match(written,/Pedido &lt;123&gt;/);
assert.match(written,/<b>OK<\/b>/);
assert.match(written,/@page\{size:85mm auto/);
assert.match(written,/window\.print\(\)/);
context.window.open=()=>null;
openPrint('X','Y','delivery');
assert.equal(toastText,'Libere pop-ups para imprimir');
console.log('Admin printing extraction: PASS');
