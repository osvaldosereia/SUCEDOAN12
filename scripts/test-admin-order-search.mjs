import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const runtime=fs.readFileSync('vitrine/admin/admin-runtime.js','utf8');
const source=fs.readFileSync('vitrine/admin/orders/search.js','utf8');
assert.ok(html.includes('/vitrine/admin/orders/search.js?v=refactor-20261018'));
assert.ok(runtime.includes('DonaAntoniaAdminOrderSearch.createOrderSearch(normalize)'));
const ctx={window:{},String,Object};
vm.runInNewContext(source,ctx);
const normalize=v=>String(v||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().trim();
const f=ctx.window.DonaAntoniaAdminOrderSearch.createOrderSearch(normalize);
const order={order_number:'DA123',customer_name:'João Silva',whatsapp_phone_e164:'5565999999999',delivery_address_snapshot:{street:'Rua São José',district:'Centro',city:'Cuiabá'},payment_method_snapshot:{label:'Pix'}};
assert.equal(f.orderSearchMatch(order,''),true);
assert.equal(f.orderSearchMatch(order,'joao'),true);
assert.equal(f.orderSearchMatch(order,'sao jose'),true);
assert.equal(f.orderSearchMatch(order,'5565999999999'),true);
assert.equal(f.orderSearchMatch(order,'pix'),true);
assert.equal(f.orderSearchMatch(order,'inexistente'),false);
assert.equal(f.orderSearchMatch(order,'DA123'),true);
assert.equal(f.orderSearchMatch(order,'centro'),true);
assert.equal(f.orderSearchMatch(order,'cuiaba'),true);
assert.equal(f.orderSearchMatch(order,'Rua São José'),true);
assert.equal(f.orderSearchMatch(order,'  '),true);
assert.equal(f.orderSearchMatch(null,'qualquer'),false);
assert.equal(f.orderSearchMatch({},'qualquer'),false);
assert.equal(f.orderSearchMatch({delivery_address_snapshot:{recipient_name:'Maria Souza'}},'maria'),true);
assert.equal(f.orderSearchMatch({payment_method_snapshot:{method:'cash'}},'cash'),true);
assert.equal(f.orderSearchMatch({delivery_address_snapshot:{phone:'5565988880000'}},'98888'),true);
assert.equal(f.orderSearchMatch({delivery_address_snapshot:{customer_name:'Beatriz'}},'beatriz'),true);
assert.equal(f.orderSearchMatch({delivery_address_snapshot:{state:'MT',number:'123'}},'mt 123'),false);
assert.equal(f.orderSearchMatch({delivery_address_snapshot:{state:'MT',number:'123'}},'123'),true);
assert.equal(f.orderSearchMatch(order,'nao existe'),false);
console.log('Admin order search: PASS');
