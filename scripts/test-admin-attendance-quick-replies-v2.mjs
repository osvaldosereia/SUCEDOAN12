import assert from 'node:assert/strict';
import fs from 'node:fs';
const html=fs.readFileSync('vitrine/admin/atendimento/index.html','utf8');
const js=fs.readFileSync('vitrine/admin/atendimento/attendance-app.js','utf8');
const css=fs.readFileSync('vitrine/admin/atendimento/attendance.css','utf8');
assert.doesNotMatch(js,/const\s+QUICK_REPLIES\s*=/,'respostas rápidas não podem ficar hardcoded');
assert.match(js,/quick_replies/,'respostas devem vir da API');
assert.match(js,/function renderQuickReplies\(\)[\s\S]*setDraft\(q\.content\)/,'respostas favoritas devem preencher o rascunho sem envio automático');
assert.doesNotMatch(js,/quick_reply_save|quick_reply_deactivate/,'gestão de respostas rápidas não está habilitada no frontend');
for(const id of ['catalogBtn','quickRepliesBtn','quickRepliesList','productsBtn','moreToolsBtn','moreToolsMenu','manageQuickRepliesBtn']) assert.match(html,new RegExp(`id=["']${id}["']`),`toolbar/painel sem ${id}`);
assert.match(html,/Criar orçamento/);assert.match(html,/Nova venda/);assert.match(html,/Marcar retorno/);assert.match(html,/Não receber ofertas/);
assert.match(css,/\.more-tools-menu|\.quick-reply/i);
assert.match(css,/\.quick-tools\{[^}]*overflow\s*:\s*auto/is,'toolbar deve permitir rolagem quando as ações não couberem');
assert.match(css,/\.quick-tools::-webkit-scrollbar\{display:none\}/,'toolbar deve ocultar a barra de rolagem visual');
console.log('OK · respostas favoritas são carregadas da API e toolbar usa Catálogo/Respostas/Produtos/Mais.');
