import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const root=read('index.html'),vitrine=read('vitrine/index.html'),resilience=read('checkout-resilience.js');
assert.equal(root,vitrine,'root and /vitrine storefronts must remain identical');
assert.match(root,/Finalizar pedido/,'ready checkout button must say Finalizar pedido');
assert.match(root,/function orderPublicUrl\(saved\)/,'checkout must build the private order summary URL');
assert.match(root,/donaantonia\.com\.br\/pedido\/\?o=/,'checkout must point to the public order summary page');
assert.match(root,/>Ver meu pedido<\/a>/,'success screen must offer the order summary');
const send=root.match(/async function sendWhatsApp\(\)\{[\s\S]*?(?=\n\s*\$\('#globalSearchForm'\))/)?.[0]||'';
assert.ok(send,'checkout submit handler must exist');
assert.ok(send.indexOf("saved=await api('submit_order'")>=0,'order must be persisted before success');
assert.ok(send.includes('renderOrderSuccess(saved)'),'success must render the saved order link');
assert.ok(!send.includes('scheduleWhatsAppReturn(url,0)'),'checkout must not force-navigation to WhatsApp after persistence');
assert.ok(!send.includes("const url='https://wa.me/'"),'checkout completion must not be driven by a company WhatsApp URL');
assert.match(resilience,/Ver meu pedido/,'stock-adjusted success must also use the order summary link');
assert.match(resilience,/donaantonia\.com\.br\/pedido\/\?o=/,'stock-adjusted success must point to the same order summary');
assert.doesNotMatch(resilience,/id="stockAdjustmentOk">OK, ir para o WhatsApp/,'stock adjustment must not force a WhatsApp redirect');
assert.match(root,/>Voltar à vitrine<\/button>/,'customer may stay on storefront');
console.log('checkout public order summary contract: ok');
