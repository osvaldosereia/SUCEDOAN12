import fs from 'node:fs';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const backend=fs.readFileSync('supabase/functions/admin-products-live-v1/index.ts','utf8');
const must=(v,m)=>{if(!v)throw new Error(m)};
const start=html.indexOf('async function finalizeDeliveredOrder(o)');
const end=html.indexOf('async function captureDeliveryPaymentAndFinish()',start);
const finalizer=html.slice(start,end);
must(finalizer.includes("order_delivery_finalize_v4"),'captured payment must use canonical V4 finalizer');
must(!finalizer.includes("order_delivery_complete_v3"),'captured payment must not be captured twice');
must(finalizer.includes("loadDeliveryRuns()"),'driver must refresh route state after delivery');
const v4=backend.slice(backend.indexOf('async function finalizeCapturedDeliveryV4('),backend.indexOf('async function reopenOrderV3('));
must(v4.includes('delivery_payment_required'),'V4 must require captured delivery payment');
must(v4.includes('delivery_payment_mismatch'),'V4 must validate captured total');
must(v4.includes('ops_sync_delivery_stop_v1'),'V4 must sync stop/run state');
const complete=backend.slice(backend.indexOf('async function completeDeliveryV3('),backend.indexOf('async function finalizeCapturedDeliveryV4('));
must(complete.includes('ops_sync_delivery_stop_v1'),'single-payment completion must sync stop/run state');
const fail=backend.slice(backend.indexOf('async function registerFailedDelivery('),backend.indexOf('async function confirmDeliveryReturn('));
must(fail.includes('ops_mark_delivery_stop_failed_v1'),'failed delivery must close stop/run when terminal');
console.log('smart delivery terminal lifecycle: ok');
