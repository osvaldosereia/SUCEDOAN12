import fs from 'node:fs';
import assert from 'node:assert/strict';
const s=fs.readFileSync('vitrine/admin/index.html','utf8');
const start=s.indexOf('  async function renderBaskets(){');
const end=s.indexOf('\n  function kitAdminCard(',start);
assert.ok(start>0&&end>start,'canonical baskets page block must exist');
const block=s.slice(start,end);
assert.match(block,/Cestas\/Kits/,'primary page must use unified Cestas/Kits term');
assert.match(block,/basket_commercial_admin/,'primary page must consume canonical admin API');
for(const slug of ['cestas-completas','cestas-so-alimento','kits-limpeza-e-higiene','kits-limpeza','kits-higiene'])assert.ok(block.includes(slug)||block.includes('category_slug'),'category filters must be data-driven from official basket categories');
for(const label of ['Editar','Novo lote','Duplicar','Pausar venda','Retomar venda'])assert.ok(block.includes(label),label+' action must exist');
assert.match(block,/public_available/,'card must display canonical public stock');
assert.match(block,/availability_reason/,'card must display canonical state/reason');
assert.doesNotMatch(block,/basket_sales_runtime|useSplitBaskets|useLegacyBaskets|Controle da vitrine e transição/,'primary page must not expose legacy/split transition controls');
assert.doesNotMatch(block,/business_type|split_kits_enabled/,'primary page must hide technical classification');
const rowStart=s.indexOf('function kitLotRow');
const rowEnd=s.indexOf('function paintBasketKitAdmin',rowStart);
const row=s.slice(rowStart,rowEnd);
assert.doesNotMatch(row,/Ativar no site|Desativar no site/,'lot editor must use pause/resume language');
assert.match(row,/Pausar venda|Retomar venda/,'lot editor must expose pause/resume language');
console.log('basket admin simple flow: PASS');
