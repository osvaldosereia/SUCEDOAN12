import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
assert.ok(html.includes('/vitrine/admin/core/identifiers.js'));
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync('vitrine/admin/core/identifiers.js','utf8'),ctx);
const f=ctx.window.DonaAntoniaAdminIdentifiers;
assert.equal(f.orderDisplayCode({public_code:'da123'}),'DA123');
assert.equal(f.orderDisplayCode({public_order_code:'AB456'}),'AB456');
assert.equal(f.orderDisplayCode({public_code:'INVALID'}),'—');
assert.equal(f.orderDisplayCode(null),'—');
assert.equal(f.phoneDigits('(65) 99999-1234'),'5565999991234');
assert.equal(f.phoneDigits('5565999991234'),'5565999991234');
assert.equal(f.formatPhone('5565999991234'),'(65) 99999-1234');
assert.equal(f.formatPhone('6533334444'),'(65) 3333-4444');
assert.equal(f.formatCpf('12345678901'),'123.456.789-01');
assert.equal(f.formatCpf('123'),'123');
console.log('Admin core identifiers: PASS');
