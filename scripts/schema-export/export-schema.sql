-- Exporta a estrutura (sem dados) dos schemas da aplicação.
-- Cada linha retorna: schema, kind, name, ddl.
-- Usado por scripts/schema-export/export-schema.mjs.
with app_schemas as (
  select n.oid, n.nspname
  from pg_namespace n
  where n.nspname in ('public','private','whatsapp_atendimento','whatsapp_ordering_private')
),
ext as (
  select 'extensions' as schema, 'extension' as kind, e.extname as name,
    format('create extension if not exists %I with schema %I;', e.extname, n.nspname) as ddl
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'
),
schemas as (
  select s.nspname, 'schema', s.nspname, format('create schema if not exists %I;', s.nspname)
  from app_schemas s where s.nspname <> 'public'
),
enums as (
  select s.nspname, 'type', t.typname,
    format('create type %I.%I as enum (%s);', s.nspname, t.typname,
      (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
  from pg_type t join app_schemas s on s.oid = t.typnamespace
  where t.typtype = 'e'
),
composites as (
  select s.nspname, 'type', t.typname,
    format('create type %I.%I as (%s);', s.nspname, t.typname,
      (select string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)), ', ' order by a.attnum)
       from pg_attribute a where a.attrelid = t.typrelid and a.attnum > 0 and not a.attisdropped))
  from pg_type t join app_schemas s on s.oid = t.typnamespace
  join pg_class c on c.oid = t.typrelid and c.relkind = 'c'
  where t.typtype = 'c'
),
seqs as (
  select s.nspname, 'sequence', c.relname,
    format('create sequence if not exists %I.%I as %s increment %s minvalue %s maxvalue %s start %s%s;',
      s.nspname, c.relname, format_type(q.seqtypid, null), q.seqincrement, q.seqmin, q.seqmax, q.seqstart,
      case when q.seqcycle then ' cycle' else '' end)
  from pg_class c join app_schemas s on s.oid = c.relnamespace
  join pg_sequence q on q.seqrelid = c.oid
  where c.relkind = 'S'
),
tables as (
  select s.nspname, 'table', c.relname,
    format(E'create table if not exists %I.%I (\n%s\n);%s%s%s',
      s.nspname, c.relname,
      concat_ws(E',\n',
        (select string_agg(
            format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
              case when a.attidentity = 'a' then ' generated always as identity'
                   when a.attidentity = 'd' then ' generated by default as identity' else '' end,
              case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                   when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
              case when a.attnotnull then ' not null' else '' end),
            E',\n' order by a.attnum)
         from pg_attribute a
         left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
         where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped),
        (select string_agg(format('  constraint %I %s', con.conname, pg_get_constraintdef(con.oid)), E',\n' order by con.contype desc, con.conname)
         from pg_constraint con where con.conrelid = c.oid and con.contype in ('p','u','c','x'))
      ),
      case when c.relrowsecurity then format(E'\nalter table %I.%I enable row level security;', s.nspname, c.relname) else '' end,
      case when c.relforcerowsecurity then format(E'\nalter table %I.%I force row level security;', s.nspname, c.relname) else '' end,
      coalesce(E'\ncomment on table ' || format('%I.%I', s.nspname, c.relname) || ' is ' || quote_literal(obj_description(c.oid, 'pg_class')) || ';', '')
    )
  from pg_class c join app_schemas s on s.oid = c.relnamespace
  where c.relkind in ('r','p')
),
fkeys as (
  select s.nspname, 'foreign_key', c.relname || '.' || con.conname,
    format('alter table %I.%I add constraint %I %s;', s.nspname, c.relname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join pg_class c on c.oid = con.conrelid
  join app_schemas s on s.oid = c.relnamespace
  where con.contype = 'f'
),
indexes as (
  select s.nspname, 'index', i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x join pg_class i on i.oid = x.indexrelid
  join pg_class c on c.oid = x.indrelid
  join app_schemas s on s.oid = c.relnamespace
  where not exists (select 1 from pg_constraint con where con.conindid = i.oid and con.contype in ('p','u','x'))
),
views as (
  select s.nspname, case c.relkind when 'm' then 'materialized_view' else 'view' end, c.relname,
    format(E'create or replace %s %I.%I%s as\n%s',
      case c.relkind when 'm' then 'materialized view' else 'view' end,
      s.nspname, c.relname,
      case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
      pg_get_viewdef(c.oid, true))
  from pg_class c join app_schemas s on s.oid = c.relnamespace
  where c.relkind in ('v','m')
),
functions as (
  select s.nspname, case p.prokind when 'p' then 'procedure' when 'a' then 'aggregate' else 'function' end,
    p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    case when p.prokind = 'a' then '-- aggregate ' || p.proname else pg_get_functiondef(p.oid) || ';' end
  from pg_proc p join app_schemas s on s.oid = p.pronamespace
  where not exists (select 1 from pg_depend dep where dep.objid = p.oid and dep.deptype = 'e')
),
triggers as (
  select s.nspname, 'trigger', c.relname || '.' || t.tgname, pg_get_triggerdef(t.oid, true) || ';'
  from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join app_schemas s on s.oid = c.relnamespace
  where not t.tgisinternal
),
policies as (
  select pol.schemaname::text, 'policy', pol.tablename || '.' || pol.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;',
      pol.policyname, pol.schemaname, pol.tablename, pol.permissive, pol.cmd,
      array_to_string(pol.roles, ', '),
      coalesce(' using (' || pol.qual || ')', ''),
      coalesce(' with check (' || pol.with_check || ')', ''))
  from pg_policies pol
  where pol.schemaname in (select nspname from app_schemas) or pol.schemaname = 'storage'
),
rel_grants as (
  select s.nspname, 'grant', c.relname,
    format('-- acl %I.%I: %s', s.nspname, c.relname, array_to_string(c.relacl, ' '))
  from pg_class c join app_schemas s on s.oid = c.relnamespace
  where c.relkind in ('r','p','v','m','S') and c.relacl is not null
),
fn_grants as (
  select s.nspname, 'function_grant', p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    format('-- acl %I.%I(%s): %s', s.nspname, p.proname, pg_get_function_identity_arguments(p.oid), array_to_string(p.proacl, ' '))
  from pg_proc p join app_schemas s on s.oid = p.pronamespace
  where p.proacl is not null
),
cron_jobs as (
  select 'cron', 'cron_job', j.jobname,
    format(E'-- active: %s\nselect cron.schedule(%L, %L, %L);', j.active, j.jobname, j.schedule, j.command)
  from cron.job j
),
buckets as (
  select 'storage', 'bucket', b.id,
    format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
      b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'null'),
      coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
  from storage.buckets b
)
select * from ext
union all select * from schemas
union all select * from enums
union all select * from composites
union all select * from seqs
union all select * from tables
union all select * from fkeys
union all select * from indexes
union all select * from views
union all select * from functions
union all select * from triggers
union all select * from policies
union all select * from rel_grants
union all select * from fn_grants
union all select * from cron_jobs
union all select * from buckets;
