import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd(),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const policy=read('supabase/functions/_shared/ana-policy-v1.mjs');
const admin=read('supabase/functions/_shared/ana-admin-config-v1.mjs');
const fixture=read('supabase/functions/_shared/ana-1018-pilot-fixture-v1.mjs');
const html=read('docs/whatsapp-1018-simulator/index.html');
const noExports=s=>s.replace(/^export\s+/gm,'');
const adminBody=admin.replace(/^import\s+\{\s*ANA_DRY_RUN_INSTRUCTIONS\s*\}\s+from\s+['"].*?['"];?\s*$/m,'');
const fixtureBody=noExports(fixture);
const htmlStart=html.indexOf('<script type="module">');
const htmlEnd=html.indexOf('</script>',htmlStart);
if(htmlStart<0||htmlEnd<0)throw Error('module script missing');
const body=html.slice(htmlStart+'<script type="module">'.length,htmlEnd);
const imports=/^import\s+\{[^}]+\}\s+from\s+['"][^'"]+['"];?\s*$/gm;
const main=body.replace(imports,'');
if(main.includes('import {'))throw Error('unexpected imports in simulator');
const standalone=html.slice(0,htmlStart)+'<script>\n'+noExports(policy)+'\n'+noExports(adminBody)+'\n'+fixtureBody+'\n'+main+'\n</script>'+html.slice(htmlEnd+'</script>'.length);
if(standalone.includes('type="module"')||standalone.includes("from '../../supabase/"))throw Error('bundle incomplete');
const output=path.join(root,'dist/whatsapp-1018-simulator/index.html');
fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,standalone);
console.log('Standalone WhatsApp 1018 simulator:',output,standalone.length,'bytes');
