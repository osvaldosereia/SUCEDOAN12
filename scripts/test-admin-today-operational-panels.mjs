import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const expiry=fs.readFileSync('vitrine/admin/components/expiry-alert.js','utf8');
const attention=fs.readFileSync('vitrine/admin/components/ops-attention.js','utf8');
assert.ok(html.includes('/vitrine/admin/components/expiry-alert.js?v=refactor-20261018'));
assert.ok(html.includes('/vitrine/admin/components/ops-attention.js?v=refactor-20261018'));
const ctx={window:{},Object,Array,Number,String};
vm.runInNewContext(expiry,ctx);
vm.runInNewContext(attention,ctx);
const esc=v=>String(v).replaceAll('<','&lt;');
const state={expiryAlerts:{summary:{total:3,due_today:1,days_1_7:2}},opsAttention:[{id:'a1',type:'bling_scope_missing',priority:'critical',summary:'Reconectar Bling',recommended_action:'Revisar escopos'}]};
const alert=ctx.window.DonaAntoniaAdminExpiryAlert.createExpiryAlert(state,esc);
assert.match(alert.renderTodayExpiryAlert(),/3 produto\(s\)/);
assert.match(alert.renderTodayExpiryAlert(),/vence\(m\) hoje/);
state.expiryAlerts={summary:{total:0}};
assert.equal(alert.renderTodayExpiryAlert(),'');
const panel=ctx.window.DonaAntoniaAdminOpsAttention.createOpsAttention(state,esc);
assert.equal(panel.attentionTargetTab({type:'bling_scope_missing'}),'bling');
assert.equal(panel.attentionTargetTab({type:'product_location_incomplete'}),'gondolas');
assert.equal(panel.attentionTargetTab({type:'papoai_legacy_endpoint'}),'more');
assert.equal(panel.attentionTargetTab({type:'other'}),'today');
assert.match(panel.renderOpsAttention(),/Reconectar Bling/);
assert.match(panel.renderOpsAttention(),/data-attention-tab="bling"/);
state.opsAttention=[];
assert.match(panel.renderOpsAttention(),/Nenhuma pendência aberta/);
state.opsAttention=null;
assert.match(panel.renderOpsAttention(),/Carregando pendências/);
console.log('Admin Today operational panels: PASS');
