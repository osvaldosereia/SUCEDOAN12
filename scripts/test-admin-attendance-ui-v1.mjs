import assert from 'node:assert/strict';
import fs from 'node:fs';

const htmlPath=new URL('../vitrine/admin/atendimento/index.html',import.meta.url);
const cssPath=new URL('../vitrine/admin/atendimento/attendance.css',import.meta.url);
const jsPath=new URL('../vitrine/admin/atendimento/attendance.js',import.meta.url);
for(const p of [htmlPath,cssPath,jsPath])assert.ok(fs.existsSync(p),`${p.pathname} deve existir`);
const html=fs.readFileSync(htmlPath,'utf8');
const css=fs.readFileSync(cssPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');

assert.match(html,/data-channel-switch="0975"/,'seletor grande do canal 0975 deve existir');
assert.match(html,/data-channel-switch="1018"/,'seletor grande do canal 1018 deve existir');
assert.match(html,/id="queueList"/,'deve existir somente uma lista visual de conversas');
assert.equal((html.match(/class="queue-list"/g)||[]).length,1,'desktop deve ter uma única fila de conversas');
assert.doesNotMatch(html,/data-filter="(?:all|unread|human)"/,'filtros Todos/Não lidos/Humano devem sair');
assert.match(html,/id="conversationPane"/);
assert.match(html,/id="contextPane"/);
for(const tab of ['Cliente','Pedidos','Produtos','Assistente'])assert.match(html,new RegExp(`>${tab}<`));
assert.doesNotMatch(html,/Kanban|pipeline|campanha/i);
assert.match(html,/id="copyReplyBtn"/);
assert.match(html,/id="openPapoAiBtn"/);
assert.match(html,/id="sendBtn"[^>]*disabled/);
assert.match(js,/ADMIN_ATTENDANCE_API/);
assert.match(js,/da_finance_access_token_v1/);
assert.match(js,/QUEUE_PAGE_SIZE\s*=\s*50/);
assert.match(js,/MESSAGE_PAGE_SIZE\s*=\s*30/);
assert.match(js,/endsWith\('0975'\)/);
assert.match(js,/endsWith\('1018'\)/);
assert.match(js,/activeChannel\s*:\s*['"]0975['"]/,'estado deve manter um único canal ativo');
assert.doesNotMatch(js,/filters\s*:\s*\{[^}]*0975[^}]*1018/s,'estado não deve manter filtros legados por canal');
assert.doesNotMatch(js,/Promise\.all\(\s*\[\s*loadQueue\(['"]0975['"]\)\s*,\s*loadQueue\(['"]1018['"]\)\s*\]\s*\)/,'refresh não pode carregar dois canais em paralelo');
assert.match(js,/function\s+switchChannel\s*\(/,'troca de canal deve ser explícita');
assert.match(js,/textContent/);
assert.match(js,/Envio pelo Admin indisponível/);
assert.match(js,/copyDraftToClipboard/);
assert.match(js,/openPapoAi/);
assert.match(js,/conversationOpen\s*:\s*false/,'estado explícito de conversa aberta deve existir');
assert.match(js,/function\s+syncConversationVisibility\s*\(/,'layout deve ser derivado do estado');
assert.match(js,/state\.conversationOpen\s*=\s*true/,'selecionar conversa deve persistir estado aberto');
assert.match(js,/function\s+fmtQueueStamp\s*\(/,'fila deve ter data/hora legível');
assert.match(js,/Hoje|Ontem/,'histórico deve reconhecer dias recentes');
assert.match(js,/message-date-separator/,'histórico deve inserir separadores de data');
assert.match(js,/canonical_last_message_at\s*\|\|\s*item\.last_message_at/,'card deve usar recência canônica');
assert.match(css,/\.message-date-separator\{/,'separador de data precisa de estilo próprio');
assert.match(css,/\.attendance-app\{[^}]*height:100vh[^}]*min-height:0[^}]*overflow:hidden/,'central deve ficar contida na altura do iframe');
assert.match(css,/\.attendance-grid\{[^}]*min-height:0[^}]*overflow:hidden/,'grid não pode criar scroll externo');
assert.match(css,/\.messages\{[^}]*min-height:0[^}]*overflow:auto/,'histórico deve rolar internamente');
assert.match(css,/@media\s*\(max-width:\s*759px\)/);
assert.match(css,/@media\s*\(min-width:\s*1180px\)/);
assert.doesNotMatch(css,/grid-template-columns:[^}]*\.72fr[^}]*\.72fr/,'desktop não deve reservar duas colunas de fila');
console.log('OK · Central v2 usa fila única, seletor de canal e timeline contida.');
