import assert from 'node:assert/strict';
import fs from 'node:fs';

const htmlPath=new URL('../vitrine/admin/atendimento/index.html',import.meta.url);
const cssPath=new URL('../vitrine/admin/atendimento/attendance.css',import.meta.url);
const jsPath=new URL('../vitrine/admin/atendimento/attendance-app.js',import.meta.url);
const authPath=new URL('../vitrine/admin/atendimento/attendance-auth.js',import.meta.url);
for(const p of [htmlPath,cssPath,jsPath,authPath])assert.ok(fs.existsSync(p),`${p.pathname} deve existir`);
const html=fs.readFileSync(htmlPath,'utf8');
const css=fs.readFileSync(cssPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
const auth=fs.readFileSync(authPath,'utf8');

assert.match(html,/data-channel-switch="all"/,'fila unificada Todas deve existir');
assert.match(html,/data-channel-switch="0975"/,'filtro 0975 deve existir');
assert.match(html,/data-channel-switch="1018"/,'filtro 1018 deve existir');
assert.match(html,/data-queue-filter="recent"/);
assert.match(html,/data-queue-filter="order"/);
assert.match(html,/data-queue-filter="pending"/);
assert.match(html,/id="queueFilterMenu"/);
assert.match(html,/id="queueLabelFilters"/);
assert.doesNotMatch(html,/data-queue-filter="unread"/,'Não lidas não deve permanecer como filtro principal');
assert.match(html,/id="queueList"/);
assert.equal((html.match(/class="queue-list"/g)||[]).length,1,'deve existir uma única fila visual');
assert.match(html,/id="conversationPane"/);
assert.match(html,/id="contextPane"/);
assert.match(html,/id="mobileChatBackBtn"/,'mobile precisa ter volta explícita para a lista de conversas');
for(const tab of ['Visão geral','Pedidos','Produtos','Assistente'])assert.match(html,new RegExp(`>${tab}<`));
assert.match(html,/id="copyReplyBtn"/,'cópia de resposta deve continuar disponível');
assert.doesNotMatch(html,/openPapoAiBtn|Abrir PapoAI/i,'atendimento não deve exibir acesso ao PapoAI');
assert.match(html,/id="sendBtn"[^>]*disabled/);
assert.doesNotMatch(html,/iframe|embedded=1|attendance-layout-v3/i,'tela nativa não pode carregar arquitetura antiga');

assert.match(js,/ADMIN_ATTENDANCE_API/);
assert.match(js,/da_finance_access_token_v1/);
assert.match(js,/QUEUE_PAGE_SIZE\s*=\s*50/);
assert.match(js,/MESSAGE_PAGE_SIZE\s*=\s*30/);
assert.match(js,/activeChannel\s*:\s*['"]all['"]/,'Todas deve ser a visão inicial');
assert.match(js,/quickFilter\s*:\s*['"]recent['"]/,'RECENTE deve ser o filtro inicial');
assert.match(js,/state\.activeChannel===['"]all['"]\?CHANNELS:\[state\.activeChannel\]/,'read side unificado deve resolver ambos os canais');
assert.match(js,/Promise\.all\(channels\.map\(channelQueue\)\)/,'0975 e 1018 devem ser lidos em paralelo na visão Todas');
assert.match(js,/function\s+switchChannel\s*\(/);
assert.match(js,/data\.items\|\|\[\]/);
assert.match(js,/conversationOpen:false/);
assert.match(js,/state\.conversationOpen=true/);
assert.match(js,/function\s+closeMobileConversation\s*\(/,'chat mobile deve poder voltar sem recarregar a página');
assert.match(js,/media-load/,'mídias devem nascer como controles leves');
assert.match(js,/trigger\.onclick=async/,'mídia só deve resolver depois do toque');
assert.doesNotMatch(js,/resolveMedia\(msg\.id\)\.then/,'chat não pode buscar imagem/áudio automaticamente ao renderizar histórico');
assert.match(js,/message-date-separator/);
assert.match(js,/canonical_last_message_at\|\|b\.last_message_at/,'fila deve ordenar pela recência canônica');
assert.match(js,/attendanceJsonApi/,'core deve delegar autenticação ao cliente compartilhado');
assert.match(auth,/ensureAttendanceToken/,'cliente compartilhado deve garantir sessão antes das chamadas');
assert.match(auth,/sessionStorage\.setItem/,'sessão renovada deve ser persistida para os demais módulos');
assert.doesNotMatch(js,/pin\s*:\s*['"]000000['"]|ADMIN_AUTH_API|admin-pin-auth-v1/,'core nativo não pode carregar autenticação embutida');
assert.doesNotMatch(js,/parent\.document|parent\.postMessage|postMessage\(/,'core nativo não pode depender da página pai');

assert.match(css,/\.attendance-workspace\{/);
assert.match(css,/\.messages\{[^}]*min-height:0[^}]*overflow:auto/,'histórico deve rolar internamente');
assert.match(css,/@media\(max-width:680px\)/,'mobile deve possuir layout próprio');
assert.match(css,/\.mobile-chat-back\{/,'mobile deve exibir botão de voltar');
assert.match(css,/\.media-load\{/,'mídias devem usar placeholder clicável');
assert.match(css,/grid-template-columns:var\(--queue\) minmax\(430px,1fr\) var\(--context\)/,'desktop deve priorizar conversa central');

console.log('OK · Atendimento nativo usa inbox unificada, cópia de resposta e não oferece acesso ao PapoAI.');
