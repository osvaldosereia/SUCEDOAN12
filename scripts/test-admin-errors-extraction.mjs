import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const source=fs.readFileSync('vitrine/admin/core/errors.js','utf8');
const tag='<script src="/vitrine/admin/core/errors.js?v=refactor-20261018"></script>';
assert.ok(html.includes(tag));
assert.ok(html.indexOf(tag)<html.indexOf('<script>\n(()=>{'));
assert.ok(html.includes('const {errorMessage}=window.DonaAntoniaAdminErrors;'));
assert.equal(html.includes('  function errorMessage(code){'),false);
const ctx={window:{},Object,String};
vm.runInNewContext(source,ctx);
const f=ctx.window.DonaAntoniaAdminErrors;
assert.ok(Object.isFrozen(f));
assert.equal(f.errorMessage('name_required'),'Informe o nome.');
assert.equal(f.errorMessage('invalid_ean'),'EAN inválido.');
assert.match(f.errorMessage('insufficient_stock'),/Estoque disponível insuficiente/);
assert.match(f.errorMessage('fiscal_generation_gate_closed'),/NF-e/);
assert.match(f.errorMessage('bling_reauthentication_required'),/Reconectar Bling/);
assert.equal(f.errorMessage('unknown_error'),'Não consegui salvar agora.');
console.log('Admin error catalog extraction: PASS');
