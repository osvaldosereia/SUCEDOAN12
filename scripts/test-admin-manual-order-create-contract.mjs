import fs from 'node:fs';
import assert from 'node:assert/strict';

const admin=fs.readFileSync('vitrine/admin/admin-runtime.js','utf8');
const backend=fs.readFileSync('supabase/functions/admin-products-live-v1/index.ts','utf8');
const begin=admin.indexOf('  async function createManualSale(){');
const end=admin.indexOf('\n  const ORDER_SEPARATORS=',begin);
assert.ok(begin>0&&end>begin,'manual order controller must exist');
const controller=admin.slice(begin,end);
assert.match(controller,/if\(!state\.manualSale\)return/);
assert.match(controller,/if\(!name\|\|!phone\|\|!street\|\|!number\|\|!city\|\|uf\.length!==2\)/);
assert.match(controller,/if\(!state\.manualSale\.cart\.length\)/);
assert.match(controller,/manualSaleTotalCents\(\)<7500/);
assert.match(controller,/api\('manual_order_create'/);
assert.match(controller,/method:'POST'/);
assert.match(controller,/customer_snapshot/);
assert.match(controller,/operator:currentOperator\(\)/);
assert.match(controller,/btn\.disabled=true/);
assert.match(controller,/btn\.disabled=false/);
const serviceBegin=backend.indexOf('async function createManualWhatsappOrder(');
const serviceEnd=backend.indexOf('\nasync function ',serviceBegin+25);
assert.ok(serviceBegin>0&&serviceEnd>serviceBegin,'manual order service must exist');
const service=backend.slice(serviceBegin,serviceEnd);
assert.match(service,/p\?\.items/);
assert.match(service,/if\(!items\.length\)/);
assert.match(service,/create_vitrine_cart_order_v3/);
assert.match(service,/create_canonical_cart_order_v2/);
assert.match(service,/p_source:"manual_whatsapp"/);
assert.match(service,/reservation_on_confirmation:true/);
assert.match(service,/stock_reserved:false/);
assert.match(service,/minimum_order/);
console.log('Admin manual order creation contract: PASS');
