import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildBasketContentsText} from '../supabase/functions/admin-whatsapp-1018-canary-v1/basket-message.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const server=read('supabase/functions/admin-whatsapp-1018-canary-v1/index.ts');
const sql=read('supabase/migrations/20261024150000_whatsapp_1018_canary_composition_v1.sql');
const ui=read('vitrine/admin/whatsapp-lab/lab.js'),html=read('vitrine/admin/whatsapp-lab/index.html');
const sample=Array.from({length:23},(_,i)=>({quantity:i%2+1,name:'Marca '+(i+1)+' Produto de cesta 1 kg'}));
const data={label:'Mini',number:1,basket:{display_price_cents:17270,stock_quantity:4},items:sample};
const text=buildBasketContentsText(data);
assert.match(text,/Cesta Mini/);
assert.match(text,/Combinação 1/);
assert.match(text,/R\$\s*172,70/);
assert.equal(text.split('\n').filter(s=>/^\d+\.\s\d+x/.test(s)).length,23);
assert.ok(text.length<4096);
assert.doesNotMatch(text,/Preço individual/);
assert.throws(()=>buildBasketContentsText({...data,basket:{...data.basket,stock_quantity:0}}),/basket_composition_unavailable/);
assert.throws(()=>buildBasketContentsText({...data,basket:{...data.basket,display_price_cents:-1}}),/basket_composition_unavailable/);
assert.throws(()=>buildBasketContentsText({...data,items:[{name:'Arroz',quantity:-1}]}),/basket_composition_invalid/);
assert.throws(()=>buildBasketContentsText({...data,items:[{name:'Arroz',quantity:1.5}]}),/basket_composition_invalid/);
assert.throws(()=>buildBasketContentsText({...data,items:Array.from({length:80},(_,i)=>({name:'Produto muito longo '.repeat(9)+' '+i,quantity:1}))}),/basket_composition_too_long/);
assert.match(server,/import \{buildBasketContentsText\} from "\.\/basket-message\.mjs"/);
assert.match(server,/\.eq\("conversation_id",pre\.conversationId\)/);
assert.match(server,/\.eq\("whatsapp_account_id",pre\.accountId\)/);
assert.match(server,/\.eq\("direction","inbound"\)\.eq\("message_type","interactive"\)/);
assert.match(server,/reply\?\.provider!=="meta"/);
assert.match(server,/replyId!==expected/);
assert.match(server,/\.eq\("kind","combinations"\)/,'Only reply to verified test combination menu');
assert.match(server,/\.eq\("status","sent"\)/);
assert.match(server,/basket_id:card\.id\+"@"\+number/);
assert.match(server,/readStorefront\("basket"/);
assert.match(server,/payload\.kind==="composition"/);
assert.match(server,/body\.kind==="composition"\?await safeComposition/);
assert.match(server,/to:DIGITS,type:"text"/,'Never accept arbitrary recipient');
assert.match(server,/\.from\(TABLE\)\.insert/,'Claim before transport');
assert.match(server,/meta_transport_uncertain/,'No unsafe retry after timeout');
assert.match(sql,/kind in \('sizes','combinations','composition'\)/);
assert.match(html,/id="sendCompositionBtn"/);
assert.match(ui,/verifiedChoiceId/);
assert.match(ui,/state\.composeDirty/);
assert.match(ui,/kind:'composition',expected_choice_id:choice/);
assert.match(ui,/confirm\('Enviar a composição ORIGINAL/);
assert.match(ui,/const LIVE_TEST_ENABLED=false/);
assert.doesNotMatch(server,/whatsapp_ana_worker|submit_order|create_order/);
console.log('PASS basket text R$ 172,70 / 23 items + server-side pricing, fixed recipient, receipt verification and canary idempotency');
