import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const source=fs.readFileSync('vitrine/admin/orders/time.js','utf8');
const runtime=fs.readFileSync('vitrine/admin/admin-runtime.js','utf8');
assert.ok(html.includes('/vitrine/admin/orders/time.js?v=refactor-20261018'));
assert.ok(runtime.includes('const {cuiabaDayKey,deliveredToday,relativeAge}=window.DonaAntoniaAdminOrderTime;'));
const ctx={window:{},Date,Intl,Number,Object,Boolean,Math};
vm.runInNewContext(source,ctx);
const f=ctx.window.DonaAntoniaAdminOrderTime;
assert.equal(f.cuiabaDayKey('2026-10-18T03:00:00Z'),'2026-10-17');
assert.equal(f.cuiabaDayKey('2026-10-18T04:00:00Z'),'2026-10-18');
assert.equal(f.cuiabaDayKey('invalid'),'');
assert.equal(f.deliveredToday({status:'confirmed'}),false);
assert.equal(f.deliveredToday({status:'delivered'}),false);
assert.equal(f.relativeAge(''), '');
assert.equal(f.relativeAge(new Date(Date.now()+60000).toISOString()),'');
assert.match(f.relativeAge(new Date(Date.now()-7200000).toISOString()),/^há 2 h$/);
assert.equal(f.cuiabaDayKey('2026-10-18T02:59:59Z'),'2026-10-17');
assert.equal(f.cuiabaDayKey('2026-10-18T03:00:00Z'),'2026-10-17');
assert.equal(f.cuiabaDayKey('2026-10-18T03:59:59Z'),'2026-10-17');
assert.equal(f.cuiabaDayKey('2026-10-18T04:00:00Z'),'2026-10-18');
assert.equal(f.relativeAge('invalid'),'');
assert.equal(f.deliveredToday(null),false);
assert.equal(f.deliveredToday({status:'delivered',delivered_at:'invalid'}),false);
console.log('Admin order time helpers: PASS');
