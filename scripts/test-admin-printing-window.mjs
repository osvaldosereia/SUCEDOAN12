import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
assert.ok(html.includes('/vitrine/admin/components/printing.js'));
const writes=[];
let opened=0,closed=0,created=0;
const popup={document:{open(){opened++},write(v){writes.push(v)},close(){closed++}}};
const ctx={window:{open(){created++;return popup}}};
vm.runInNewContext(fs.readFileSync('vitrine/admin/components/printing.js','utf8'),ctx);
const escapeHtml=v=>String(v).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const notifications=[];
const openPrint=ctx.window.DonaAntoniaAdminPrinting.createOpenPrint(v=>notifications.push(v),escapeHtml);
openPrint('Pedido <123>','<p>Separação</p>','receipt',popup);
assert.equal(created,0);
assert.equal(opened,1);
assert.equal(closed,1);
assert.match(writes[0],/<title>Pedido &lt;123&gt;<\/title>/);
assert.match(writes[0],/<body class="receipt"><p>Separação<\/p>/);
assert.match(writes[0],/window\.print\(\)/);
assert.deepEqual(notifications,[]);
const blocked={window:{open(){return null}}};
vm.runInNewContext(fs.readFileSync('vitrine/admin/components/printing.js','utf8'),blocked);
const blockedNotifications=[];
blocked.window.DonaAntoniaAdminPrinting.createOpenPrint(v=>blockedNotifications.push(v),escapeHtml)('Teste','', 'receipt');
assert.deepEqual(blockedNotifications,['Libere pop-ups para imprimir']);
console.log('Admin printing window: PASS');
