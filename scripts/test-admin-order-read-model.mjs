import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const source=fs.readFileSync('vitrine/admin/orders/read-model.js','utf8');
assert.ok(html.includes('/vitrine/admin/orders/read-model.js?v=refactor-20261018'));
assert.ok(html.includes('DonaAntoniaAdminOrderReadModel.createOrderReadModel(cuiabaDayKey,state)'));
const ctx={window:{},Date,Object,String,Array,Boolean,Number};
vm.runInNewContext(source,ctx);
const state={orders:[],orderIssueFilter:'all'};
const day=v=>v instanceof Date?'2026-10-18':String(v).slice(0,10);
const f=ctx.window.DonaAntoniaAdminOrderReadModel.createOrderReadModel(day,state);
const good={status:'created',created_at:'2026-10-18T10:00:00Z',customer_name:'Cliente',delivery_address_snapshot:{street:'Rua',city:'Cuiabá'},payment_method_snapshot:{label:'Pix'}};
const missing={...good,customer_name:'',delivery_address_snapshot:{},payment_method_snapshot:{}};
assert.equal(Array.from(f.orderProblemReasons(good)).length,0);
assert.ok(Array.from(f.orderProblemReasons(missing)).includes('Cliente não identificado'));
assert.ok(Array.from(f.orderProblemReasons(missing)).includes('Endereço incompleto'));
assert.ok(Array.from(f.orderProblemReasons(missing)).includes('Pagamento não informado'));
assert.equal(f.orderNextAction(good),'Confirmar pedido');
assert.equal(f.orderNextAction({...good,status:'confirmed'}),'Iniciar separação');
assert.equal(f.orderNextAction({...good,status:'confirmed',payment_method_snapshot:{stock_consumed:true}}),'Continuar separação');
assert.equal(f.orderNextAction({...good,status:'processing',payment_method_snapshot:{stock_consumed:true}}),'Finalizar separação');
assert.equal(f.orderOperationalPriority(missing),0);
assert.equal(f.isBacklogOrder({...good,created_at:'2026-10-17T10:00:00Z'}),true);
assert.equal(f.orderFilterMatch({...good,status:'confirmed'},'separate'),true);
assert.equal(f.orderFilterMatch({...good,status:'delivered'},'separate'),false);
state.orders=[good,missing];
assert.equal(f.orderIssueCount('all'),1);
assert.equal(f.orderFilterMatch(missing,'problems'),true);
assert.equal(f.orderProblemReasons({...missing,status:'delivered'}).length,0);
console.log('Admin order read model: PASS');
