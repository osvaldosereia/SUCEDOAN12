import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync('vitrine/admin/orders/session.js','utf8'),context);
let open=true;
const session=context.window.DonaAntoniaAdminOrderSession.create({isOpen:()=>open});
const old=session.begin('a');session.detail={order:{id:'a'}};session.fiscal={stage:'blocked'};session.preview={old:true};
assert.equal(session.isCurrent(old),true);
const fresh=session.begin('b');
assert.equal(session.detail,null);assert.equal(session.fiscal,null);assert.equal(session.preview,null);
assert.equal(session.isCurrent(old),false);
session.detail={order:{id:'b'}};
const first=session.request('fiscal'),second=session.request('fiscal');
assert.equal(session.accepts(first),false);assert.equal(session.accepts(second),true);
open=false;assert.equal(session.isCurrent(fresh),false);
open=true;session.invalidate();assert.equal(session.isCurrent(fresh),false);
const reopened=session.begin('b');session.detail={order:{id:'b'}};
assert.equal(session.isCurrent(fresh),false);assert.equal(session.isCurrent(reopened),true);
session.detail={order:{id:'c'}};
assert.equal(session.isCurrent(reopened),false,'external replacement must invalidate ownership');
assert.equal(session.capture().id,'c');
assert.ok(Object.isFrozen(session));
console.log('Admin order session ownership: PASS');
