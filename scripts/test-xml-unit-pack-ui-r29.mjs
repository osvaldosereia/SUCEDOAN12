import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const html=readFileSync('vitrine/admin/index.html','utf8');
const start=html.indexOf('  function xmlCatalogDetailMarkup(){');
const end=html.indexOf('  function bindXmlCatalog(){',start);
assert(start>=0&&end>start,'catalog detail UI must be present');
const ui=html.slice(start,end);
assert.match(ui,/id="xmlDetailGtinSource"/,'explicit XML GTIN source');
assert.match(ui,/id="xmlDetailRole"/,'base-unit/package GTIN role');
assert.match(ui,/id="xmlDetailFactorWrap"/,'EAN package factor is separate');
assert.match(ui,/id="xmlDetailPurchasePackUnits"[^>]*placeholder="Não confirmado"/,'purchase packaging is optional');
assert.match(ui,/packRaw===''\?null:Number\(packRaw\)/,'empty package count is unverified');
assert.match(ui,/!outer&&factor\)factor.value='1'/,'individual GTIN factor remains one');
assert.match(ui,/purchase_pack_units_for_review:packUnits/,'UI passes separate evidence-only pack');
assert.match(ui,/id="xmlDetailNewName"[^>]*value="" placeholder="Nome comercial por unidade/,'never default to supplier pack name');
assert.match(ui,/conversion_factor:factor/,'existing unit factor still required');
assert.match(ui,/catalog_evidence_only:true/,'catalog-only operation');
assert.match(ui,/CRIAR_INATIVO_XML/,'human confirmation');
assert.match(ui,/Não calcula nem lança estoque/,'pack unit is not stock receipt');
assert.doesNotMatch(ui,/id="xmlDetailPurchasePackUnits"[^>]*value="12"/,'do not infer 12 from supplier string');
console.log('PASS R29 UI: individual EAN, optional unapproved pack, no supplier name or guessed 12');
