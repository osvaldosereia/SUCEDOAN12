import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const visual=require('../vitrine/admin/orders-visual-v1.js');
assert.equal(typeof visual.resolveState,'function','Módulo visual precisa expor resolveState');
assert.equal(visual.resolveState(['CONFIRMADO']),'confirmed','Confirmado deve aguardar separação em verde');
assert.equal(visual.resolveState(['CONFIRMADO','SEPARADO']),'separated','Separado deve assumir destaque laranja');
assert.equal(visual.resolveState(['CONFIRMADO','SEPARADO','ENTREGUE']),'neutral','Entregue não deve continuar com fundo de separação');
assert.equal(visual.resolveState(['CANCELADO','CONFIRMADO']),'neutral','Cancelado não deve receber destaque operacional');
const src=fs.readFileSync(new URL('../vitrine/admin/orders-visual-v1.js',import.meta.url),'utf8');
assert.match(src,/order-status-confirmed-tag/,'Tag CONFIRMADO precisa ter classe de destaque');
assert.match(src,/order-status-separated-tag/,'Tag SEPARADO precisa ter classe de destaque');
assert.match(src,/order-separation-ready/,'Botão de separação precisa ter classe verde discreta');
assert.match(src,/MutationObserver/,'Decoração precisa acompanhar re-render dos cards');
const loader=fs.readFileSync(new URL('../vitrine/admin/basket-admin-section.js',import.meta.url),'utf8');
assert.match(loader,/orders-visual-v1\.js\?v=20261005-1/,'Loader do Admin precisa carregar o destaque dos pedidos');
assert.match(loader,/basket-admin-section-core\.js\?v=canonical-v3/,'Loader precisa preservar o módulo canônico de Cestas/Kits');
console.log('orders visual v1 contract: ok');
