import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {JSDOM}=require(process.env.TEST_RUNTIME?`${process.env.TEST_RUNTIME}/node_modules/jsdom`:'jsdom');
const html=readFileSync('comprar/index.html','utf8'),js=readFileSync('comprar/chat-light.js','utf8');
const dom=new JSDOM(html,{url:'https://donaantonia.com.br/comprar/?s='+'a'.repeat(64),runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,calls=[],timers=[];
w.DA_SHOPPING_ROOM_CONFIG={api:'https://example.test/chat'};
w.scrollTo=()=>{};
w.requestAnimationFrame=fn=>{fn();return 1};
w.setTimeout=(fn,delay)=>{timers.push({fn,delay});return timers.length};w.clearTimeout=()=>{};
w.navigator.geolocation={getCurrentPosition:(ok)=>ok({coords:{latitude:-15.6,longitude:-56.1,accuracy:12}})};
const basket={id:'11111111-1111-4111-8111-111111111111',name:'Cesta Família',base_price:299.9,image_url:null,description:'Cesta completa'};
const product={id:'22222222-2222-4222-8222-222222222222',name:'Arroz 5kg',price:29.9,image_url:null,brand:'Marca',packaging:'5kg',quantity:0};
w.fetch=async(_url,opts)=>{
 const body=opts.body instanceof w.FormData?{action:opts.body.get('action')} : JSON.parse(opts.body);calls.push(body);let result={ok:true};
 if(body.action==='open')result={...result,session:{entry_intent:'baskets',entry_source:'whatsapp'},customer:{id:'customer-1',name:'João Cliente',phone:'65999999999'},baskets:[basket],cart:null,messages:[]};
 if(body.action==='baskets')result={...result,baskets:[basket]};
 if(body.action==='start_basket')result={...result,items:[{product_id:product.id,quantity:1,product}],cart:{total:299.9,items:[{product_id:product.id,quantity:1,source:'basket',product}]}};
 if(body.action==='set_basket_quantity')result={...result,cart:{total:299.9,items:[{product_id:product.id,quantity:2,source:'basket',product}]}};
 if(body.action==='products')result={...result,products:[product]};
 if(body.action==='set_quantity')result={...result,cart:{total:329.8,items:[{product_id:product.id,quantity:1,source:'addon',product}]}};
 if(body.action==='checkout_preview')result={...result,checkout:{customer:{id:'customer-1',name:'João Cliente',phone:'65999999999'},requires_document:false,cart:{total:329.8},items:[{quantity:1,name:'Cesta Família',source:'basket',line_total:299.9}],addresses:[{street:'Rua teste',number:'1',neighborhood:'Centro',city:'Cuiabá',state:'MT'}]},payment_method:null};
 if(body.action==='set_payment')result={...result,payment_method:body.payment_method};
 if(body.action==='confirm_order')result={...result,order:{total:329.8,id:'order-1'}};
 if(body.action==='messages')result={...result,messages:[]};
 return {ok:true,json:async()=>result};
};
const flush=async()=>{for(let i=0;i<15;i++)await new Promise(r=>setImmediate(r));};
try{
 w.eval(js);await flush();
 assert.match(w.document.querySelector('#timeline').textContent,/Oi João!/);
 assert.match(w.document.querySelector('#timeline').textContent,/Cesta Família/);
 const basketButton=[...w.document.querySelectorAll('button')].find(x=>x.textContent==='Ver esta cesta');assert.ok(basketButton);
 basketButton.click();await flush();
 assert.match(w.document.querySelector('#timeline').textContent,/Edite a cesta original primeiro/);
 assert.match(w.document.querySelector('#timeline').textContent,/Arroz 5kg/);
 const ready=[...w.document.querySelectorAll('button')].find(x=>x.textContent==='Pronto com a cesta');assert.ok(ready);ready.click();await flush();
 assert.ok([...w.document.querySelectorAll('button')].some(x=>x.textContent==='Finalizar pedido'));
 const finish=[...w.document.querySelectorAll('button')].find(x=>x.textContent==='Finalizar pedido');finish.click();await flush();
 assert.match(w.document.querySelector('#timeline').textContent,/Cadastro identificado/);
 const pix=[...w.document.querySelectorAll('.pay')].find(x=>x.textContent==='PIX');assert.ok(pix);pix.click();await flush();
 assert.equal(calls.find(x=>x.action==='set_payment').payment_method,'pix');
 const locate=w.document.querySelector('#useLocation');locate.click();await flush();assert.match(w.document.querySelector('#locationStatus').textContent,/recebida/i);
 const confirm=[...w.document.querySelectorAll('button')].find(x=>x.textContent==='Confirmar pedido');confirm.click();await flush();
 const orderCall=calls.find(x=>x.action==='confirm_order');assert.equal(orderCall.payment_method,'pix');assert.equal(orderCall.delivery_address.street,'Rua teste');assert.equal(orderCall.delivery_locator.lat,-15.6);
 assert.match(w.document.querySelector('#timeline').textContent,/Pedido recebido/);
 console.log('PASS: lightweight chat keeps WhatsApp context, basket rail, edit, checkout, payment, locator and confirmation.');
}finally{w.close();}
