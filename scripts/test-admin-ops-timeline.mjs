import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const source=fs.readFileSync('vitrine/admin/components/ops-timeline.js','utf8');
assert.ok(html.includes('/vitrine/admin/components/ops-timeline.js?v=refactor-20261018'));
const ctx={window:{},Object,Array,String};
vm.runInNewContext(source,ctx);
const state={opsTimeline:[]};
const f=ctx.window.DonaAntoniaAdminOpsTimeline.createOpsTimeline(state,v=>String(v).replaceAll('<','&lt;'),v=>'18/10/2026');
assert.equal(f.renderOpsTimeline(),'');
state.opsTimeline=[{source_system:'storefront',severity:'error',summary:'Pedido recebido',actor_label:'Operador',occurred_at:'2026-10-18'}];
assert.match(f.renderOpsTimeline(),/Site/);
assert.match(f.renderOpsTimeline(),/Pedido recebido/);
assert.match(f.renderOpsTimeline(),/18\/10\/2026/);
assert.match(f.renderOpsTimeline(),/pill danger/);
state.opsTimeline=[{source_system:'dona_antonia',summary:'<script>'}];
assert.ok(!f.renderOpsTimeline().includes('<script>'));
console.log('Admin ops timeline: PASS');
