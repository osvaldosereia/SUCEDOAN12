import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {stripTypeScriptTypes} from 'node:module';
const path='supabase/functions/basket-lot-image-v1/core.ts';
assert.ok(fs.existsSync(path),'a composição de imagem do lote precisa existir');
const code=stripTypeScriptTypes(fs.readFileSync(path,'utf8'),{mode:'strip'}).replaceAll('export ','');
const ctx={crypto:globalThis.crypto,TextEncoder,URL};vm.createContext(ctx);vm.runInContext(code,ctx);
const items=[{product_id:'rice',quantity_per_basket:3,product:{name:'Arroz',image_url:'https://example.com/rice.webp'}},{product_id:'rice',quantity_per_basket:1,product:{name:'Arroz',image_url:'https://example.com/rice.webp'}},{product_id:'oil',quantity_per_basket:2,product:{name:'Óleo',image_url:'https://example.com/oil.webp'}}];
ctx.items=items;
assert.deepEqual(JSON.parse(vm.runInContext('JSON.stringify(imageManifest(items))',ctx)).map(x=>[x.product_id,x.quantity]),[['rice',4],['oil',2]],'produtos repetidos precisam de uma foto e quantidade somada por cesta');
ctx.items=[{product_id:'x',quantity_per_basket:1,product:{name:'Sem foto'}}];
assert.throws(()=>vm.runInContext('imageManifest(items)',ctx),/product_image_missing/);
ctx.items=[{product_id:'x',quantity_per_basket:1.5,product:{name:'Fracionado',image_url:'x'}}];
assert.throws(()=>vm.runInContext('imageManifest(items)',ctx),/invalid_unit_quantity/);
ctx.items=items;
const key1=await vm.runInContext('manifestHash(imageManifest(items),"food","hygiene")',ctx);
items[0].quantity_per_basket=2;
const key2=await vm.runInContext('manifestHash(imageManifest(items),"food","hygiene")',ctx);
assert.notEqual(key1,key2,'alterar quantidade deve invalidar a prévia');
assert.equal(vm.runInContext('sourceAllowed("https://127.0.0.1/a")',ctx),false);
assert.equal(vm.runInContext('sourceAllowed("https://ssbesxgaijknwsjbsbcz.supabase.co/storage/v1/object/public/product-images/a.webp")',ctx),true);
assert.equal(vm.runInContext('validFinalWebp(new Uint8Array(51001))',ctx),false);
console.log('Basket image manifest, freshness and source guards passed');
