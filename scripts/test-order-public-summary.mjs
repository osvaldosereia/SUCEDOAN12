import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const migration=read('supabase/migrations/20261003024500_order_public_summary.sql');
const edge=read('supabase/functions/order-public-view-v1/index.ts');
const page=read('pedido/index.html');
const admin=read('vitrine/admin/index.html');
assert.match(migration,/order_public_snapshots_v1/,'snapshot table required');
assert.match(migration,/enable row level security/i,'snapshot table must have RLS');
assert.match(migration,/revoke all on table public\.order_public_snapshots_v1 from anon, authenticated/i,'snapshot table must not be directly public');
assert.match(migration,/create constraint trigger trg_order_item_public_snapshot_v1/i,'checkout snapshot must use a deferred constraint trigger');
assert.match(migration,/deferrable initially deferred/i,'snapshot must be generated only at transaction end after all items exist');
assert.match(migration,/if exists \([\s\S]*order_public_snapshots_v1[\s\S]*new\.order_id/i,'later deferred item triggers must no-op after the first immutable snapshot');
assert.match(edge,/ops2_refresh_order_public_snapshot_v1/,'old orders must be lazily snapshot-able');
assert.match(edge,/Cache-Control":"private, no-store/,'public endpoint must not cache private order data');
assert.match(page,/name="robots" content="noindex,nofollow,noarchive"/,'order page must not be indexed');
assert.match(page,/name="referrer" content="no-referrer"/,'secret order id must not leak through referrers');
assert.match(page,/Produtos do pedido/,'page must show order products');
assert.match(page,/Produtos avulsos/,'standalone products section required');
assert.match(page,/Quantidade:/,'quantities must be visible');
assert.match(admin,/function publicOrderUrlFor/,'admin must reuse the order summary link');
const company=admin.slice(admin.indexOf('function currentOrderCompanyWhatsappMessage'),admin.indexOf('function openNativeWhatsapp'));
const customer=admin.slice(admin.indexOf('function currentOrderCustomerWhatsappMessage'),admin.indexOf('function openCurrentOrderCustomerWhatsapp'));
assert.match(company,/Conferir pedido completo/,'company message must send the order link');
assert.match(customer,/Confira produtos, fotos, quantidades e entrega/,'customer manual message must send the order link');
assert.ok(!company.includes('appendCurrentOrderWhatsappItems'),'company message must no longer paste the full product list');
assert.ok(!customer.includes('appendCurrentOrderWhatsappItems'),'customer manual message must no longer paste the full product list');
console.log('public order summary + shared admin link contract: ok');
