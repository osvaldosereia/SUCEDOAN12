import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('vitrine/admin/index.html','utf8');
const runtime=fs.readFileSync('vitrine/admin/admin-runtime.js','utf8');
const source=fs.readFileSync('vitrine/admin/components/today-cards.js','utf8');
assert.ok(html.includes('/vitrine/admin/components/today-cards.js?v=refactor-20261018'));
assert.ok(runtime.includes('createTodayCards(esc,todayCardCount,orderIssueCount)'));
const ctx={window:{},Object,String,Number};
vm.runInNewContext(source,ctx);
const f=ctx.window.DonaAntoniaAdminTodayCards.createTodayCards(v=>String(v),key=>key==='new'?3:0,key=>key==='stock'?2:0);
const cards=f.renderTodayCards();
assert.match(cards,/Pedidos para confirmar/);
assert.match(cards,/data-today-filter="new"/);
assert.match(cards,/>3<\/strong>/);
assert.match(cards,/data-today-issue="stock"/);
assert.match(cards,/Estoque · 2/);
const empty=ctx.window.DonaAntoniaAdminTodayCards.createTodayCards(v=>v,()=>0,()=>0);
assert.equal(empty.renderTodayIssueBreakdown(),'');
assert.match(cards,/data-today-tab="closure"/);
assert.match(cards,/data-today-filter="backlog"/);
assert.match(cards,/data-today-filter="problems"/);
assert.equal((cards.match(/class="ops-card /g)||[]).length,8);
assert.match(cards,/data-today-issue="stock"/);
assert.ok(!cards.includes('data-today-issue="payment"'));
const escapeHtml=v=>String(v).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const guarded=ctx.window.DonaAntoniaAdminTodayCards.createTodayCards(escapeHtml,()=>0,()=>0);
assert.match(guarded.renderTodayCards(),/Pedidos para confirmar/);
assert.equal(guarded.renderTodayIssueBreakdown(),'');
console.log('Admin today cards: PASS');
